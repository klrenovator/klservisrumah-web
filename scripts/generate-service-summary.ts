// ── Dedicated-tool cards ──────────────────────────────────────────────────
// `ServiceEstimatorBlock` links six services to their hand-built calculator and
// renders that tool's name plus three headline stats. Reading them from
// `config/tools-data.ts` shipped ~150 KB of every calculator's full copy deck to
// the browser on all 28 service pages and all 112 sub-service pages.
const dedicatedToolCards = Object.fromEntries(
  [...new Set(Object.values(DEDICATED_TOOL_BY_SERVICE))].map((toolSlug) => {
    const tool = toolsContent[toolSlug];
    if (!tool) throw new Error(`DEDICATED_TOOL_BY_SERVICE references unknown tool "${toolSlug}"`);
    return [toolSlug, { slug: tool.slug, name: tool.name, stats: tool.stats.map(({ label, value }) => ({ label, value })) }];
  })
);

