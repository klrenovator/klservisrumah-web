// ── Quote catalog ─────────────────────────────────────────────────────────
// The multi-step booking form and the MS/ZH pricing page need each service's
// sub-service *price* and *description*, which the lean service summary above
// deliberately omits. Without this file both components imported the full
// `config/services-data.ts` registry (~470 KB source / ~429 KB emitted chunk)
// into the browser just to render a picker — see the performance notes in
// lib/smart-finder-loader.ts. This carries only the fields those two screens
// actually render.
type QuoteCatalogSubService = { name: string; price: string; desc: string };
type QuoteCatalogEntry = {
  slug: string;
  title: string;
  startPrice: string;
  tagline: string;
  warranty: string;
  subServices: QuoteCatalogSubService[];
  i18n?: Partial<Record<Locale, {
    title: string;
    tagline: string;
    warranty: string;
    subServices: QuoteCatalogSubService[];
  }>>;
};

const quoteCatalog = Object.fromEntries(
  Object.entries(servicesData).map(([slug, service]) => {
    const pickSubs = (subs: typeof service.subServices): QuoteCatalogSubService[] =>
      subs.map(({ name, price, desc }) => ({ name, price, desc }));

    const entry: QuoteCatalogEntry = {
      slug: service.slug,
      title: service.title,
      startPrice: service.startPrice,
      tagline: service.tagline,
      warranty: service.warranty,
      subServices: pickSubs(service.subServices),
    };

    const locales = Object.entries(service.i18n ?? {}).map(([locale, localized]) => [
      locale,
      {
        title: localized.title || service.title,
        tagline: localized.tagline || service.tagline,
        warranty: localized.warranty || service.warranty,
        subServices: pickSubs(
          localized.subServices?.length ? localized.subServices : service.subServices
        ),
      },
    ]);

    if (locales.length) {
      entry.i18n = Object.fromEntries(locales);
    }

    return [slug, entry];
  })
);

